function row = basic_case_summary(r)
% One compact, directly plottable row per basic grid point and k.
timingAndImpulse=nan(1,3);
if ~isempty(r.variables), timingAndImpulse=r.variables(4:6); end
row=table(r.caseId,r.gridId,r.basic(1),r.basic(2),r.basic(3),r.k,...
 timingAndImpulse(1),timingAndImpulse(2),timingAndImpulse(3),...
 string(r.status),r.feasible,r.cost,r.maxViolation,r.speed,r.cot,r.energy,...
 r.distance,r.stanceTime,r.flightTime,r.vz0,r.starts,r.convergedStarts,...
 r.iterations,r.functionEvaluations,r.elapsed,r.seed,r.exitflag,string(r.errorIdentifier),...
 'VariableNames',{'caseId','gridId','vx0','thetaL','r0','k','stanceScale','duty','Ix','status','feasible',...
 'cost','maxViolation','speed','CoT','energy','distance','stanceTime','flightTime','vz0',...
 'starts','convergedStarts','iterations','functionEvaluations','elapsed','seed','exitflag','errorIdentifier'});
end
